// --- Global Variables ---
let modalData = {};
let currentFilter = 'all';
let currentLimit = 6; 

// Initialize components when DOM is fully loaded
document.addEventListener('DOMContentLoaded', () => {
    // Only run if we are on the portfolio page
    if (document.getElementById('portfolio-grid')) {
        loadCMSData();
    }
});

/**
 * CMS Connection Logic
 * Fetches JSON data generated by Decap CMS. Falls back to static data if not found.
 */
async function loadCMSData() {
    try {
        const response = await fetch('data/portfolio.json');
        if (!response.ok) throw new Error('CMS JSON data not found');
        
        const data = await response.json();
        
        if (data && data.works && data.works.length > 0) {
            console.log("CMS Service: Connected & Data Loaded 🚀");
            renderDynamicGrid(data.works);
        } else {
            throw new Error('JSON loaded but no works found');
        }
    } catch (err) {
        console.warn("CMS offline or data missing, using local fallbacks.", err);
        renderFallbackGrid();
    }
}

/**
 * Converts CMS JSON array into HTML Grid and populates Modal Data
 * @param {Array} works - Array of project objects from CMS
 */
function renderDynamicGrid(works) {
    const grid = document.getElementById('portfolio-grid');
    grid.innerHTML = ''; // Clear canvas
    modalData = {}; // Reset modal data

    const catLabels = {
        'uiux': 'UI/UX',
        'photo': 'Photo Editing',
        'manipulation': 'Image Manipulation',
        'video': 'Video Editing',
        '3d': '3D Modeling',
        'graphic': 'Graphic Design'
    };

    works.forEach((work, index) => {
        const uniqueKey = 'cms_project_' + index;
        const displayTag = catLabels[work.category] || work.category;

        // Build Modal Data dynamically
        modalData[uniqueKey] = {
            tag: displayTag,
            title: work.title,
            title_zh: work.title_zh, 
            desc: work.description,
            desc_zh: work.description_zh, 
            tools: work.tools,
            year: work.year,
            client: work.client,
            client_zh: work.client_zh 
        };

        // Inject HTML Card
        grid.innerHTML += `
            <div class="portfolio-item" data-cat="${work.category}" onclick="openModal('${uniqueKey}')">
              <div class="portfolio-bg">
                <img src="${work.thumbnail}" alt="${work.title}" class="portfolio-img" onerror="this.src='Image/Logo_Colour.png'">
              </div>
              <div class="portfolio-overlay"></div>
              <div class="portfolio-info">
                <span>${displayTag}</span>
                <h3>${work.title}</h3>
              </div>
            </div>
        `;
    });

    updatePortfolioGrid(); // Apply UI logic
}

/**
 * Renders the static fallback data if CMS data is unavailable
 */
function renderFallbackGrid() {
    const grid = document.getElementById('portfolio-grid');
    grid.innerHTML = ''; 
    modalData = fallbackData; // Use hardcoded fallback

    Object.keys(fallbackData).forEach(key => {
        const work = fallbackData[key];
        
        grid.innerHTML += `
            <div class="portfolio-item" data-cat="${work.category}" onclick="openModal('${key}')">
              <div class="portfolio-bg">
                <img src="${work.thumbnail}" alt="${work.title}" class="portfolio-img">
              </div>
              <div class="portfolio-overlay"></div>
              <div class="portfolio-info">
                <span>${work.tag}</span>
                <h3>${work.title}</h3>
              </div>
            </div>
        `;
    });

    updatePortfolioGrid();
}

/**
 * Filters items based on the selected category
 */
function filterPortfolio(category, btnElement) {
    const buttons = document.querySelectorAll('.filter-btn');
    buttons.forEach(btn => btn.classList.remove('active'));
    
    if (btnElement) {
        btnElement.classList.add('active');
    }

    currentFilter = category;
    currentLimit = 6; 
    updatePortfolioGrid();

    // ✨ 切换分类时重新触发动画效果
    setTimeout(() => {
        if (typeof applyPortfolioAnimations === 'function') {
            // 先清除当前的 AOS 动画状态
            const allCards = document.querySelectorAll('.portfolio-item');
            allCards.forEach(card => card.classList.remove('aos-animate'));
            
            // 短暂延迟后再次触发
            setTimeout(() => {
                applyPortfolioAnimations();
            }, 50);
        }
    }, 50);
}

/**
 * Loads more items by increasing the display limit
 */
function loadMoreItems() {
    currentLimit += 6; 
    updatePortfolioGrid();
}

/**
 * Core function to update grid visibility and Bento layout
 */
function updatePortfolioGrid() {
    const items = document.querySelectorAll('.portfolio-item');
    const loadMoreContainer = document.getElementById('load-more-container');
    let visibleItems = [];

    // ✨ 新逻辑：处理过滤条件
    if (currentFilter === 'all') {
        // 当处于 "ALL WORK" 模式时，用 Set 来记录已经展示过的分类
        const seenCategories = new Set();
        
        items.forEach(item => {
            const itemCat = item.getAttribute('data-cat');
            // 如果这个分类还没被展示过，就把它加入显示列表 (即每个分类的第一个最新作品)
            if (!seenCategories.has(itemCat)) {
                seenCategories.add(itemCat);
                visibleItems.push(item);
            } else {
                item.style.display = 'none'; 
                item.classList.remove('bento-large'); 
            }
        });
    } else {
        // 普通的单分类模式逻辑：只显示对应分类的作品
        items.forEach(item => {
            const itemCat = item.getAttribute('data-cat');
            if (itemCat === currentFilter) {
                visibleItems.push(item);
            } else {
                item.style.display = 'none'; 
                item.classList.remove('bento-large'); 
            }
        });
    }

    // 2. Apply limit and dynamic Bento grid layout
    visibleItems.forEach((item, index) => {
        if (index < currentLimit) {
            item.style.display = 'flex'; 
            
            // Bento logic: Pattern for spanning 2 columns
            if (index % 4 === 0 || index % 4 === 3) {
                item.classList.add('bento-large');
            } else {
                item.classList.remove('bento-large');
            }
        } else {
            item.style.display = 'none'; 
        }
    });

    // 3. Toggle "Load More" button visibility
    if (loadMoreContainer) {
        loadMoreContainer.style.display = (visibleItems.length > currentLimit) ? 'block' : 'none';
    }
}

