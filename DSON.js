// --- Global Variables ---
let modalData = {};           // Stores project details for modals
let allWorksData = [];        // Raw project list from CMS
let currentFilter = 'all';    // Active category filter
let currentLimit = 6;         // Items limit for specific categories
let currentGallery = [];      // Array for active modal's images
let currentGalleryIndex = 0;  // Index for active modal's slider

// --- 1. System Initialization ---
document.addEventListener('DOMContentLoaded', () => {
    const langLinks = document.querySelectorAll('.lang-switcher a');
    
    // ✨ Memory: Load saved language preference
    const savedLang = localStorage.getItem('selectedLang');
    if (savedLang && langLinks.length > 0) {
        langLinks.forEach(link => {
            const isZhBtn = link.innerText.includes('中文');
            if ((savedLang === 'zh' && isZhBtn) || (savedLang === 'en' && !isZhBtn)) {
                link.classList.add('active');
            } else {
                link.classList.remove('active');
            }
        });
    }

    // Sync static text on page immediately
    syncAllLanguage();

    // Kickstart CMS data loading if on portfolio page
    if (document.getElementById('portfolio-grid')) {
        loadCMSData();
    }

    // Language Switcher Global Listener
    langLinks.forEach(link => {
        link.addEventListener('click', (e) => {
            e.preventDefault();
            langLinks.forEach(l => l.classList.remove('active'));
            link.classList.add('active');
            
            const isChinese = link.innerText.includes('中文');
            localStorage.setItem('selectedLang', isChinese ? 'zh' : 'en');
            
            syncAllLanguage();
            
            // If a modal is open, we re-render it to refresh its language
            const overlay = document.getElementById('modal-overlay');
            if (overlay.classList.contains('open')) {
                const activeKey = overlay.getAttribute('data-current-key');
                if (activeKey) openModal(activeKey);
            }
        });
    });
});

// --- 2. Data Engine & Rendering ---

/**
 * Fetch JSON data generated by CMS
 */
async function loadCMSData() {
    const grid = document.getElementById('portfolio-grid');
    try {
        const response = await fetch('data/portfolio.json');
        if (!response.ok) throw new Error('Portfolio JSON not found');
        
        const data = await response.json();
        if (data && data.works && data.works.length > 0) {
            console.log("CMS Data: Loaded successfully 🚀");
            allWorksData = data.works;
            renderPortfolioUI();
        }
    } catch (err) {
        console.warn("CMS Connection failed. Using placeholder or empty grid.", err);
        if(grid) grid.innerHTML = '';
    }
}

/**
 * Core Render Logic: Orchestrates Grid & Load More Button
 */
function renderPortfolioUI() {
    const grid = document.getElementById('portfolio-grid');
    const loadMoreContainer = document.getElementById('load-more-container');
    if (!grid) return;

    grid.innerHTML = ''; 
    modalData = {}; // Clear previous session data

    const catLabels = {
        'uiux': { en: 'UI/UX', zh: 'UI/UX 设计' },
        'photo': { en: 'Photo Editing', zh: '照片后期' },
        'manipulation': { en: 'Image Manipulation', zh: '图像合成' },
        'video': { en: 'Video Editing', zh: '视频制作' },
        '3d': { en: '3D Modeling', zh: '3D 建模' },
        'graphic': { en: 'Graphic Design', zh: '平面设计' }
    };

    let displayList = [];

    if (currentFilter === 'all') {
        // ✨ SMART HOME LOGIC: Get exactly the latest 1 project from each of the 6 core categories
        const categories = ['video', 'uiux', 'manipulation', '3d', 'graphic', 'photo']; 
        categories.forEach(cat => {
            const latest = allWorksData.find(w => w.category === cat);
            if (latest) displayList.push(latest);
        });
        if (loadMoreContainer) loadMoreContainer.style.display = 'none';
    } else {
        // ✨ CATEGORY MODE: Filter by selected tag and apply current limit for pagination
        const filtered = allWorksData.filter(w => w.category === currentFilter);
        displayList = filtered.slice(0, currentLimit);
        
        if (loadMoreContainer) {
            loadMoreContainer.style.display = (filtered.length > currentLimit) ? 'block' : 'none';
        }
    }

    // Build Grid Cards with Multilingual Metadata
    displayList.forEach((work, index) => {
        const uniqueKey = 'proj_' + index;
        const labels = catLabels[work.category] || { en: work.category, zh: work.category };

        // Save to global modal storage
        modalData[uniqueKey] = { ...work, labels };

        // Bento Grid Logic (Desktop)
        const bentoClass = (index % 4 === 0 || index % 4 === 3) ? 'bento-large' : '';

        grid.innerHTML += `
            <div class="portfolio-item ${bentoClass}" onclick="openModal('${uniqueKey}')">
              <div class="portfolio-bg">
                <img src="${work.thumbnail}" alt="${work.title}" class="portfolio-img" onerror="this.src='Image/Logo_Colour.png'">
              </div>
              <div class="portfolio-overlay"></div>
              <div class="portfolio-info">
                <span class="lang-en">${labels.en}</span>
                <span class="lang-zh">${labels.zh}</span>
                <h3 class="lang-en">${work.title}</h3>
                <h3 class="lang-zh">${work.title_zh || work.title}</h3>
              </div>
            </div>
        `;
    });

    syncAllLanguage(); 
    applyPortfolioAnimations(); 
}

/**
 * Handles category selection from the filter bar
 */
function filterPortfolio(category, btnElement) {
    const buttons = document.querySelectorAll('.filter-btn');
    buttons.forEach(btn => btn.classList.remove('active'));
    if (btnElement) btnElement.classList.add('active');

    currentFilter = category;
    currentLimit = 6; 
    renderPortfolioUI();
}

/**
 * Loads the next batch of projects in category view
 */
function loadMoreItems() {
    currentLimit += 6; 
    renderPortfolioUI();
}

// --- 3. Animation & Language Systems ---

function applyPortfolioAnimations() {
    const items = document.querySelectorAll('.portfolio-item');
    if (items.length > 0) {
        items.forEach((card, index) => {
            card.removeAttribute('data-aos');
            card.classList.remove('aos-animate');
            void card.offsetWidth; 

            const animationType = (index % 2 === 0) ? 'fade-right' : 'fade-left';
            card.setAttribute('data-aos', animationType);
            card.setAttribute('data-aos-delay', (index % 6) * 50); 
        });

        AOS.init({
            duration: 1000,
            easing: 'ease-out-cubic',
            once: true,
            offset: 0 
        });
        
        AOS.refreshHard(); 
    }
}

function syncAllLanguage() {
    const lang = localStorage.getItem('selectedLang') || 'en';
    const enNodes = document.querySelectorAll('.lang-en');
    const zhNodes = document.querySelectorAll('.lang-zh');

    if (lang === 'zh') {
        enNodes.forEach(el => el.style.setProperty('display', 'none', 'important'));
        zhNodes.forEach(el => el.style.setProperty('display', 'block', 'important'));
    } else {
        enNodes.forEach(el => el.style.setProperty('display', 'block', 'important'));
        zhNodes.forEach(el => el.style.setProperty('display', 'none', 'important'));
    }
}

// --- 4. Modal Engine (Full Features & Fixes) ---

