/**
 * Closes modal when clicking on the overlay
 */
function closeModal(e) {
    const overlay = document.getElementById('modal-overlay');
    if (e.target === overlay) {
        overlay.classList.remove('open');
    }
}

/**
 * Creates and opens a full-screen Lightbox for image zooming
 * @param {string} imgSrc - The source URL of the image to enlarge
 */
function openLightbox(imgSrc) {
    let lightbox = document.getElementById('lightbox-overlay');
    
    // Create the lightbox element dynamically if it doesn't exist
    if (!lightbox) {
        lightbox = document.createElement('div');
        lightbox.id = 'lightbox-overlay';
        // Modern glassmorphism backdrop for the zoom view
        lightbox.style.cssText = 'position: fixed; top: 0; left: 0; width: 100vw; height: 100vh; background: rgba(10, 10, 10, 0.85); backdrop-filter: blur(8px); z-index: 9999; display: flex; justify-content: center; align-items: center; cursor: zoom-out; opacity: 0; transition: opacity 0.3s ease;';
        
        lightbox.innerHTML = `<img id="lightbox-img" src="" style="max-width: 90vw; max-height: 90vh; border-radius: 8px; box-shadow: 0 20px 50px rgba(0,0,0,0.6); transform: scale(0.95); transition: transform 0.3s cubic-bezier(0.175, 0.885, 0.32, 1.275);">`;
        
        // Close lightbox on click with animation
        lightbox.onclick = function() {
            lightbox.style.opacity = '0';
            document.getElementById('lightbox-img').style.transform = 'scale(0.95)';
            setTimeout(() => { lightbox.style.display = 'none'; }, 300);
        };
        
        document.body.appendChild(lightbox);
    }
    
    const img = document.getElementById('lightbox-img');
    img.src = imgSrc;
    
    lightbox.style.display = 'flex';
    
    // Trigger animation frame for silky smooth fade-in and pop effect
    requestAnimationFrame(() => {
        lightbox.style.opacity = '1';
        img.style.transform = 'scale(1)';
    });
}

// Global Event Listeners for UX
document.addEventListener('keydown', e => {
    if (e.key === 'Escape') {
        // Priority 1: Close lightbox if it's open
        const lightbox = document.getElementById('lightbox-overlay');
        if (lightbox && lightbox.style.display === 'flex') {
            lightbox.click();
            return;
        }
        
        // Priority 2: Close modal if lightbox is not open
        const overlay = document.getElementById('modal-overlay');
        if (overlay && overlay.classList.contains('open')) {
            overlay.classList.remove('open');
        }
    }
});