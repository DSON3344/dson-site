/**
 * Fullscreen Image Lightbox Node (性能优化极致丝滑版 ✨)
 */
function openLightbox(imgSrc) {
    let lightbox = document.getElementById('lightbox-overlay');
    if (!lightbox) {
        lightbox = document.createElement('div');
        lightbox.id = 'lightbox-overlay';
        
        // ✨ 优化1：移除极其消耗手机性能的 backdrop-filter，改用 98% 纯黑背景，并开启 opacity 硬件加速
        lightbox.style.cssText = 'position:fixed; top:0; left:0; width:100vw; height:100vh; background:rgba(8,10,15,0.98); z-index:10000; display:flex; justify-content:center; align-items:center; cursor:zoom-out; opacity:0; transition:opacity 0.3s ease; display:none; will-change: opacity;';
        
        // ✨ 优化2：减小阴影渲染压力，开启 transform 硬件加速，确保动画 60fps 丝滑
        lightbox.innerHTML = `<img id="lightbox-img" src="" style="max-width:92vw; max-height:92vh; border-radius:6px; box-shadow:0 10px 25px rgba(0,0,0,0.5); transform:scale(0.95); transition:transform 0.3s cubic-bezier(0.165, 0.84, 0.44, 1); will-change: transform; object-fit: contain;">`;
        
        document.body.appendChild(lightbox);
        
        // 关闭逻辑
        lightbox.onclick = () => {
            lightbox.style.opacity = '0';
            document.getElementById('lightbox-img').style.transform = 'scale(0.95)';
            setTimeout(() => { lightbox.style.display = 'none'; }, 300);
        };
    }
    
    const img = document.getElementById('lightbox-img');
    img.src = imgSrc;
    lightbox.style.display = 'flex';
    
    // ✨ 优化3：使用底层强制回流 (Reflow) 替代玄学定时器，确保动画瞬间顺滑触发
    void lightbox.offsetWidth;
    
    lightbox.style.opacity = '1';
    img.style.transform = 'scale(1)';
}

// Keyboard Navigation
document.addEventListener('keydown', e => {
    // Escape: Close Lightbox or Modal
    if (e.key === 'Escape') {
        const lb = document.getElementById('lightbox-overlay');
        if (lb && lb.style.display === 'flex') return lb.click();
        const mo = document.getElementById('modal-overlay');
        if (mo && mo.classList.contains('open')) closeModal({ target: mo });
    }
    // Arrows: Control Modal Gallery
    if (document.getElementById('modal-gallery-img')) {
        if (e.key === 'ArrowRight') changeGalleryImage(1);
        if (e.key === 'ArrowLeft') changeGalleryImage(-1);
    }
});

// Scroll Events: Back to Top Trigger
document.addEventListener('scroll', () => {
    const btn = document.getElementById('backToTopBtn');
    if (btn) (window.scrollY > 500) ? btn.classList.add('show') : btn.classList.remove('show');
});

window.scrollToTop = () => {
    window.scrollTo({ top: 0, behavior: 'smooth' });
}